#include <stdio.h>
//Data Types
/*
 a variable in C must be a specified data type, and you must use a 
 format specifier inside the printf() function to display it:*/

 int main(){
    int myNum = 5; 
    float myFloatNum = 5.99;
    char myLetter = 'D';

    printf("\n%i", myNum);
    printf("\n%f", myFloatNum);
    printf("\n%c", myLetter);

 }

